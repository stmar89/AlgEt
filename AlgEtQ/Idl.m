/// Returns a $\mathbb{Z}$-basis of the fractional ideal.
intrinsic ZBasis(I::AlgEtQIdl)->SeqEnum[AlgEtQElt]
{Returns a Z-basis of the fractional ideal.}
    if not assigned I`ZBasis then
        assert assigned I`Generators;
        assert not assigned I`Hash; //if Hash is assigned then a ZBasis has been computed
        A:=Algebra(I);
        S:=Order(I);
        gens:=[g*s : g in Generators(I) , s in ZBasis(S) ];
        if #Generators(I) eq 1 then
            zb:=gens; //gens is a ZBasis of I
        else
            H,d:=lattice_hnf(gens);
            zb:=MatrixQtoA(A,(1/d)*crZQ(H));
            assert #zb eq AbsoluteDimension(A);
            I`Hash:=hash_from_hnf(H,d);
        end if;
        I`ZBasis:=zb;
    end if;
    return I`ZBasis;
end intrinsic;

intrinsic Generators(I::AlgEtQIdl) -> SeqEnum[AlgEtQElt]
{Returns a set of generators of the fractional ideal.}
    if not assigned I`Generators then
        I`Generators:=ZBasis(I);
    end if;
    assert2 #I`Generators le AbsoluteDimension(Algebra(I));
    return I`Generators;
end intrinsic;

///## Hashing and equality
/// Let $I$ a fractional $S$-ideal in an étale algebra over $\mathbb{Q}$.
/// Let $P$ be the upper triangular Hermite normal form of the integer square matrix $d\cdot M$ where $M$ is the matrix whose rows are the coefficients of a $\mathbb{Z}$-basis of $I$ and $d$ is the least common denominator of its entries.
/// The `Hash` of $I$ is defined to be the sequence consisting of the least common denominator of $\frac{1}{d}\cdot P$ and the entries of the upper triangular part of $\frac{1}{d}\cdot P$.
/// This hashing method has no collisions and it is independent of the choice of $\mathbb{Z}-basis$ from which we start the procedure.
/// We observed that applying the in-built Hash function to the sequence defined above, while giving a smaller hash, it often leads to collisions. For this reason, equality is tested using the whole sequence.
/// The intrinsic `Hash` returns an integer computed from this sequence, which is used by Magma to build sets, indexed sets and associative arrays of fractional ideals: only ideals with the same hash value are compared with `eq`, so collisions only cost an extra comparison.

intrinsic myHash(I::AlgEtQIdl)->SeqEnum[RngInt]
{Hash function.}
    if not assigned I`Hash then
        H,d:=lattice_hnf(ZBasis(I));
        assert2 IsUpperTriangular(H);
        I`Hash:=hash_from_hnf(H,d);
    end if;
    return I`Hash;
end intrinsic;

/// Returns a hash value of the fractional ideal, so that equal ideals have the same hash value. It is computed from the sequence returned by `myHash` and it is stored in the attribute `HashValue`. Magma uses it to build sets, indexed sets and associative arrays of ideals: only ideals with the same hash value are compared with `eq`. Different ideals might have the same hash value: this only costs an extra comparison.
intrinsic Hash(I::AlgEtQIdl) -> RngIntElt
{Returns a hash value of the fractional ideal, so that equal ideals have the same hash value. It is computed from the sequence returned by myHash and it is stored in the attribute HashValue. Magma uses it to build sets, indexed sets and associative arrays of ideals: only ideals with the same hash value are compared with eq. Different ideals might have the same hash value: this only costs an extra comparison.}
    if not assigned I`HashValue then
        // The entries of myHash(I) are integers, but its universe is Rationals().
        // Since the universe matters, e.g. Hash([1,2]) ne Hash([1/1,2/1]), we make sure it is
        // Integers().
        I`HashValue:=Hash(ChangeUniverse(myHash(I),Integers()));
    end if;
    return I`HashValue;
end intrinsic;

intrinsic 'eq'(I::AlgEtQIdl , J::AlgEtQIdl ) -> BoolElt
{Equality testing.}
    require Algebra(I) cmpeq Algebra(J) : "The ideals are not in the same algebra.";
    require Order(I) cmpeq Order(J) : "The ideals are not over the same order.";
    if  (not (assigned I`Hash and assigned J`Hash)) and
        (assigned I`Generators and assigned J`Generators and Generators(I) eq Generators(J)) then
        // to compute myHash we need compute an HNF. In this way we might avoid it.
        out:=true;
        //note that the set of generators is not unique for an ideal.
    else
        out:=myHash(I) eq myHash(J);
    end if;
    if out then //we copy the attributes
        // The attributes that depend on the ZBasis are copied only together with the ZBasis itself.
        zb_dep:={"inclusion_matrix","IsZBasisLLLReduced","IsZBasisLLLFromHNF"};
        zbI:=assigned I`ZBasis;
        zbJ:=assigned J`ZBasis;
        for att in GetAttributes(AlgEtQIdl) do
            if att notin zb_dep then
                if assigned I``att and not assigned J``att then
                    J``att:=I``att;
                elif assigned J``att and not assigned I``att then
                    I``att:=J``att;
                end if;
            end if;
        end for;
        if zbI ne zbJ then
            X,Y:=Explode(zbI select <I,J> else <J,I>); // Y got the ZBasis of X above
            for att in zb_dep do
                if assigned X``att then
                    Y``att:=X``att;
                end if;
            end for;
        end if;
    end if;
    return out;
end intrinsic;

