///## Various properties of the ideals

/// Returns if the argument is a product of ideals in the number fields defining the algebra. If so, it returns also the sequence of these ideals (in the appropriate orders). We require the order of definition of the ideal to be its multiplicator ring.
intrinsic IsProductOfIdeals(I::AlgEtQIdl) -> BoolElt, Tup
{Returns if the argument is a product of ideals in the number fields defining the algebra. If so, it returns also the sequence of these ideals (in the appropriate orders). Note: we require Order(I) to be the MultiplicatorRing(I).}
    if not assigned I`IsProductOfIdeals then
        O:=Order(I);
        require O eq MultiplicatorRing(I) : "The ideal needs to be defined over its multiplicator ring.";
        A:=Algebra(O);
        test,orders:=IsProductOfOrders(O);
        if test then
            nf,_,projs:=Components(A);
            zb:=ZBasis(I);
            ideals:=< ideal< orders[i] | [ projs[i](z) : z in zb ] > : i in [1..#orders] >;
            I`IsProductOfIdeals:=<true, ideals>;
        else
            I`IsProductOfIdeals:=<false,<>>;
        end if;
    end if;
    return Explode(I`IsProductOfIdeals);
end intrinsic;

/// Given two integral ideals $I$ and $J$ over the same order $S$, returns whether $I+J=S$.}
intrinsic IsCoprime(I::AlgEtQIdl,J::AlgEtQIdl) -> BoolElt
{Given two integral ideals I and J over the same order S, returns whether I+J=S.}
    require Algebra(I) cmpeq Algebra(J) : "the ideals must lie in the same algebra";
    S:=Order(J);
    require Order(I) eq S: "the ideals must be over the same order";
    if I eq J then
        return I eq OneIdeal(S); // I+I = I
    end if;
    if assigned I`IsPrime and assigned J`IsPrime then
        if IsPrime(I) and IsPrime(J) then
            return true; //we already know that the ideals are distinct
        end if;
    end if;
    require IsIntegral(I) and IsIntegral(J): "the ideals must be integral";
    g:=GCD(MinimalInteger(I),MinimalInteger(J));
    if g eq 1 then
        return true;
    else
        return (One(S) in I+J); //here we generate a new ideal, which is expensive.
    end if;
end intrinsic;

intrinsic IsIntegral(I::AlgEtQIdl) -> BoolElt
{Returns whether the given fractional ideal is integral in its order of definition.}
    if not assigned I`IsIntegral then
        S:=Order(I);
        I`IsIntegral:=I subset S;
    end if;
    return I`IsIntegral;
end intrinsic;

/// Given a fractional $S$-ideal $I$, returns the ideal $d*I$, where $d$ is the smallest integer such that $d\cdot I$ is integral. Compare with the intrinsic `SmallRepresentative`.
intrinsic MakeIntegral(I::AlgEtQIdl) -> AlgEtQIdl,RngIntElt
{Given a fractional S-ideal I, returns the ideal d*I,d when d is the smallest integer such that d*I is integral in S. Compare with SmallRepresentative.}
    if IsIntegral(I) then return I,1; end if;
    S:=Order(I);
    d:=LCM(&cat[ [Denominator(x_coord) : x_coord in x] : x in AbsoluteCoordinates(Generators(I),S)]);
    dI:=d*I;
    assert2 dI subset S;
    return dI, d;
end intrinsic;

intrinsic MinimalInteger(I::AlgEtQIdl) -> RngIntElt
{Returns the smallest integer contained in the given fractional ideal, which must be integral.}
    if not assigned I`MinimalInteger then
        require IsIntegral(I): "the ideal must be integral";
        ZZ:=Integers();
        coord:=AbsoluteCoordinates([One(Algebra(I))],I)[1];
        min:=LCM([ Denominator(c) : c in Eltseq(coord)]);
        assert2 min in I;
        I`MinimalInteger:=min;
    end if;
    return I`MinimalInteger;
end intrinsic;


coprime_rep_from_primes:=function(I,Iinv,zb,pp)
// Given an invertible fractional S-ideal I, its inverse Iinv, a short Z-basis zb of Iinv and the
// sequence pp of the primes of S containing an integral ideal J, returns x in Iinv, not a
// zero-divisor, such that x*I is coprime to J, that is, x is not in Q*Iinv for any Q in pp. It is
// built prime by prime, without the CRT (whose idempotents cost a CRT over all the primes each, too
// much when there are many primes):
//  - xs[k] is an element of Iinv not in pp[k]*Iinv;
//  - es[k] is a product of elements of S, one in each pp[j] with j ne k but not in pp[k], so es[k]
//    is in every pp[j] with j ne k and, pp[k] being prime, not in pp[k].
// Then x:=&+[ es[k]*xs[k] ] is congruent to es[k]*xs[k] modulo pp[k]*Iinv, and es[k]*xs[k] is not
// in pp[k]*Iinv: locally at pp[k], Iinv is generated by one element w (I is invertible), xs[k]=u*w
// with u a unit at pp[k], and es[k]*u is not in pp[k]. Finally x is replaced by a short element of
// its class modulo L:=(Q_1...Q_r)*Iinv, which does not change its class modulo any pp[k]*Iinv. The
// choices use only data which depend on the lattices (zb, which in CoprimeRepresentative depends
// only on Iinv, the minimal integers and the HNF bases of the primes), so the output depends only
// on I and pp.
    A:=Algebra(I);
    // the smallest positive integer in a full lattice L: the lcm of the denominators of the
    // coordinates of 1
    min_int:=func< L | LCM([ Denominator(c) : c in AbsoluteCoordinates([One(A)],L)[1] ]) >;
    if #pp eq 0 then
        return A!min_int(Iinv); // J = S: any non-zero-divisor of Iinv works, for example an integer
    end if;
    gI:=Generators(I);
    // x is in Q*Iinv if and only if x*g is in Q for every generator g of I, since I is invertible
    not_in_QIinv:=func< x,Q | exists{ g : g in gI | not x*g in Q } >;
    // xs[k] is an element of Iinv not in pp[k]*Iinv: it exists since pp[k]*Iinv ne Iinv
    xs:=[ [ z : z in zb | not_in_QIinv(z,Q) ][1] : Q in pp ];
    // An element of the prime P not in the prime Q ne P: the rational prime below P if Q is above
    // another one; otherwise an element of the HNF basis of P (whose entries are smaller than the
    // rational prime), which exists since P is not contained in Q.
    r:=#pp;
    ps:=[ MinimalInteger(P) : P in pp ];
    hnf_basis:=function(P)
        if assigned P`Hash then
            d:=P`Hash[1]; // the denominator of the lattice
            H:=hnf_from_hash(P`Hash,d); // free
        else
            H,d:=lattice_hnf(ZBasis(P));
        end if;
        return MatrixQtoA(A,(1/d)*crZQ(H));
    end function;
    hnfs:=[ ps[j] in Remove(ps,j) select hnf_basis(pp[j]) else [] : j in [1..r] ]; // only if needed
    elt_in_not_in:=func< j,k | ps[j] ne ps[k] select A!ps[j] else [ z : z in hnfs[j] | not z in pp[k] ][1] >;
    if r eq 1 then
        x:=xs[1];
    else
        es:=[ &*[ elt_in_not_in(j,k) : j in [1..r] | j ne k ] : k in [1..r] ];
        x:=&+[ es[k]*xs[k] : k in [1..r] ];
    end if;
    // Adding an element of L does not change the class of x modulo any pp[k]*Iinv.
    L:=(&*pp)*Iinv;
    // the LLL reduction of the HNF of L, so that the short element depends only on L
    ZBasisLLL(L : FromHNF:=true);
    x:=ShortElementModulo(x,L);
    if IsZeroDivisor(x) then
        // This can happen only if J has no prime in some component of A: then x is not determined
        // there modulo L. We add a multiple of the smallest positive integer y in L: x+t*y is a
        // zero-divisor for at most one t per component.
        y:=min_int(L);
        t:=1;
        while IsZeroDivisor(x+t*y) do
            t+:=1;
        end while;
        x:=x+t*y;
    end if;
    assert2 forall{ Q : Q in pp | not_in_QIinv(x,Q) };
    return x;
end function;

/// Given an invertible fractional ideal $I$ and an integral ideal $J$, defined over the same order, returns a unit $x$ of the parent algebra such that $x\cdot I$ is an integral fractional ideal coprime with $J$, together with the product $x\cdot I$. The output depends only on $I$ and $J$ (it is not random), and $x$ is a short element of $I^{-1}$, so $x\cdot I$ is small. If $I$ is already integral and coprime with $J$, then $x=1$, unless the vararg `MakeSmall` is set to true: then $x$ is always a short element of $I^{-1}$, so that $x\cdot I$ is small also in this case.
intrinsic CoprimeRepresentative(I::AlgEtQIdl,J::AlgEtQIdl : MakeSmall:=false) -> AlgEtQElt,AlgEtQIdl
{Given an invertible fractional ideal I and an integral ideal J, defined over the same order, returns a unit x of the parent algebra such that x*I is an integral fractional ideal coprime with J, together with the product x*I. The output depends only on I and J (it is not random), and x is a short element of I^-1, so x*I is small. If I is already integral and coprime with J, then x=1, unless the vararg MakeSmall is set to true: then x is always a short element of I^-1, so that x*I is small also in this case.}
    require IsIntegral(J) : "the second ideal must be integral";
    S:=Order(I);
    require S eq Order(J): "the ideals must be defined over the same order";
    A:=Algebra(I);
    // Let Q_1,...,Q_r be the primes of S containing J. For x in I^-1, x*I is integral, and x*I+J=S
    // if and only if x is not in Q_k*I^-1 for every k, that is, if and only if for every k some
    // x*g, with g a generator of I, is not in Q_k. We try candidates in a fixed order: 1 if I is
    // integral, then short elements of I^-1, from the LLL reduction of the HNF of I^-1, which
    // depends only on the lattice (see the vararg FromHNF of ZBasisLLL).
    // If the primes of J are known (for example for the conductor, see SingularPrimes) a candidate
    // is tested with the memberships above; otherwise with IsCoprime, which does not need them: J
    // is factored only if no candidate works (then x is built prime by prime, see
    // coprime_rep_from_primes), which can happen when there are many primes with small residue
    // fields.
    known_primes:=assigned J`PrimesAbove or assigned J`Factorization;
    if known_primes then
        pp:=PrimesAbove(J);
        gI:=Generators(I);
        is_good:=func< x | forall{ Q : Q in pp | exists{ g : g in gI | not x*g in Q } } >;
    else
        is_good:=func< x | IsCoprime(x eq One(A) select I else x*I,J) >;
    end if;
    if not MakeSmall and IsIntegral(I) and is_good(One(A)) then
        x:=One(A);
    else
        Iinv:=Inverse(I); // cached
        // the LLL reduction of the HNF of Iinv, stored in Iinv: it depends only on the lattice
        ZBasisLLL(Iinv : FromHNF:=true);
        zb:=ZBasis(Iinv);
        found:=false;
        for z in short_non_zero_divisors(zb,30) do
            if is_good(z) then
                x:=z;
                found:=true;
                break;
            end if;
        end for;
        if not found then
            vprintf AlgEtQIdl,2: "CoprimeRepresentative: no candidate works, we build one prime by prime\n";
            x:=coprime_rep_from_primes(I,Iinv,zb,PrimesAbove(J));
        end if;
    end if;
    xI:=x eq One(A) select I else x*I;
    assert2 IsIntegral(xI) and IsCoprime(xI,J) and not IsZeroDivisor(x);
    vprintf AlgEtQIdl,2: "CoprimeRepresentative:\n
                            I = %o\n,xI = %o\n",PrintSeqAlgEtQElt(ZBasis(I)),PrintSeqAlgEtQElt(ZBasis(xI));
    return x,xI;
end intrinsic;

