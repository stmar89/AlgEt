///## Coercion of fractional ideals
/// Let $S$ and $T$ be orders in an étale algebra and let $I$ be a fractional $S$-ideal.
/// If $T \subseteq S$ then $I$ is naturally also a fractional $T$-ideal.
/// Otherwise, one can consider the fractional $T$-ideal $IT$ generated by $I$.
/// This is done using the operator `!!`.

/// Given an order $T$ and a fractional $S$-ideal $I$ for some order $S$ in the same étale algebra of $T$, returns the fractional $T$-ideal $IT$. If $T$ is a subset of $S$, then $IT$ and $I$ coincides as sets.
intrinsic '!!'(T::AlgEtQOrd,I::AlgEtQIdl) -> AlgEtQIdl
{Given an order T and a fractional S-ideal I for some order S in the same étale algebra of T, returns the fractional T-ideal IT. If T is a subset of S, then IT and I coincides as sets.}
    if Order(I) eq T then
        return I;
    elif T subset Order(I) then
        //in this case, Generators of I might not be a generating set over T
        id:=Ideal(T,ZBasis(I));
        id`ZBasis:=ZBasis(I); //the ZBasis stays the same..
        if assigned I`MultiplicatorRing then
            id`MultiplicatorRing:=I`MultiplicatorRing; //..as well as the MultiplicatorRing
        end if;
        // ..and the hash, which depends only on the lattice
        if assigned I`Hash then
            id`Hash:=I`Hash;
        end if;
        if assigned I`HashValue then
            id`HashValue:=I`HashValue;
        end if;
        return id;
    else //in this case Order(I) is strictly contained in T
        // The extensions of I to the maximal order and to the multiplicator ring of I are computed
        // often: we store them in I. The extensions to other orders are not stored, to keep the
        // memory bounded. We check that the cached order is identical to the passed one with
        // IsIdentical. It has an effect only when CheckIsKnownOrder:=false. It is very cheap since
        // it is only a pointer check.
        to_max:=assigned T`IsMaximal and T`IsMaximal;
        to_mr:=(not to_max) and assigned I`MultiplicatorRing and T eq I`MultiplicatorRing;
        if to_max and assigned I`ExtensionToMaximalOrder and IsIdentical(Order(I`ExtensionToMaximalOrder),T) then
            return I`ExtensionToMaximalOrder;
        elif to_mr and assigned I`ExtensionToMultiplicatorRing and IsIdentical(Order(I`ExtensionToMultiplicatorRing),T) then
            return I`ExtensionToMultiplicatorRing;
        end if;
        out:=Ideal(T,Generators(I));
        if (assigned T`IsMaximal and IsMaximal(T)) or (assigned I`IsInvertible and IsInvertible(I)) then
            out`IsInvertible:=true;
            out`MultiplicatorRing:=T;
        end if;
        if to_max then
            I`ExtensionToMaximalOrder:=out;
        elif to_mr then
            I`ExtensionToMultiplicatorRing:=out;
        end if;
        return out;
    end if;
end intrinsic;

