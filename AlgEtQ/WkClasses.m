units_T_mod_P_gens:=function(T,P)
// Let P be a prime of an order S and T=(P:P), so that A:=T/P is a finite S/P-algebra.
// Returns a sequence of elements of T whose images in A generate the unit group A^*.
// Let qq be the primes of T above P.
// Then J:=meet(qq) is the radical of P in T, m:=J/P is the Jacobson radical of A, and A/m = prod_q T/q. 
// Since A is commutative with nilpotent m then the sequence
//   1 → 1+m → A^* → (A/m)^* → 1
// is exact.
// Hence A^* is generated by:
// - for each q in qq, a lift of a generator of (T/q)^* which is congruent to 1 modulo the other primes;
// - the subgroup 1+m, which is generated by the elements 1+b for b in ZBasis(J^i), i=1,2,4,8,..., until J^i c P.
//   Indeed, put U_i:=1+m^i. For x,y in m^i we have (1+x)(1+y)=1+(x+y)+xy with xy in m^(2i), so x:->1+x induces an
//   isomorphism of abelian groups m^i/m^(2i) -> U_i/U_(2i). 
//   Since m^i is the image of J^i, the images of ZBasis(J^i) generate m^i, and hence 
//   the elements 1+b, b in ZBasis(J^i), generate U_i/U_(2i).
//   Let H be the subgroup generated by all the 1+b above, and let 2^M be the first power with J^(2^M) c P, so that
//   U_(2^M)=1 is contained in H. If H contains U_(2i) and u is in U_i, pick h in H with h = u mod U_(2i); then
//   u*h^-1 is in U_(2i) c H, so u is in H. Descending over i=2^(M-1),...,2,1 gives H=U_1=1+m.
//   References: Serre, Local Fields, Ch. IV §2 (the proof there only uses xy in m^(2i));
//   Cohen, Advanced Topics in Computational Number Theory, §4.2 uses the same chain U_1 > U_2 > U_4 > ...
    A:=Algebra(T);
    TP:=T!!P;
    qq:=PrimesAbove(TP);
    gens:=[];
    // semisimple part generated by lifts generators of (A/m)^*=prod_q (T/q)^*.
    for i->q in qq do
        c:=PrimitiveElementResidueField(q);
        if #qq gt 1 then
            rest:=&meet[ qq[j] : j in [1..#qq] | j ne i ]; // coprime ideals: meet = product, but faster
            c:=ChineseRemainderTheorem(q,rest,c,One(A));
        end if;
        Append(~gens,c);
    end for;
    // unipotent part: 1+m, using the chain J, J^2, J^4, ... until J^(2^M) c P.
    J:=#qq eq 1 select qq[1] else &meet qq;
    Ji:=J;
    while not Ji subset TP do
        gens cat:=[ One(A)+b : b in ZBasis(Ji) ];
        Ji:=Ji*Ji;
    end while;
    return gens;
end function;

is_mult_ring_S:=function(Q,k,A_basis,W)
// Input:
// - Q=I/PI, a k=S/P-vector space, where I is a fractional (P:P)-ideal and P is a singular prime of S;
// - A_basis, a k-basis of the image of A:=(P:P)/P in End_k(Q), given as matrices acting on the right on Q;
// - W, a sub-k-vector space of Q, so that J:=q^-1(W) is a fractional S-ideal satisfying PI c J c I.
// It requires that A->End_k(Q) is injective. Needs to be checked by the caller.
// Output:
// - a boolean = is (J:J)=S ?
// The function returns the answer without computing J, but working only with W. 
// This allows us to use fast linear algebra over finite fields, and keeps coefficients small.
// Why it works: for x in T:=(P:P) we have xJ c J if and only if x.W c W, since xPI c PI holds automatically.
// Hence (J:J) is the preimage of Stab_A(W):={ a in A : W.a c W } under T->A=T/P, and (J:J)=S if and only if
// Stab_A(W)=k.1, that is, if and only if Stab_A(W) has k-dimension 1.
    Q_W, proj := quo<Q|W>; // Q_W = Q/W = I/J
    if Dimension(Q_W) eq 0 then
        return false;  // J=I is a (P:P)-module, and (P:P) is strictly bigger than S.
    end if;
    // a = sum_j lambda_j*A_basis[j] stabilizes W if and only if proj(v*a)=0 for every v in Basis(W).
    // The rows of R_mat are indexed by j; the vectors lambda such that lambda*R_mat=0 give the stabilizer.
    R_mat := Matrix(k,[ &cat[ Eltseq(proj((Q!v)*a)) : v in Basis(W) ] : a in A_basis ]);
    return Dimension(Kernel(R_mat)) eq 1; // Kernel returns the left kernel.
end function;

wkicm_bar_with_P_P:=function(I,P,gensU)
// Input:
// - P, a prime of an order S. Put T:=(P:P).
// - I, a fractional T-ideal, that is, Order(I) eq T.
// - gensU, a sequence of elements of T whose images generate (T/P)^*, as returned by units_T_mod_P_gens(T,P).
// Output: representatives of the weak equivalence classes of the fractional S-ideals J such that
//         P*I c J c I, (J:J)=S and J*T=I.
// If I is invertible in T, then I is replaced by T (this does not change the output up to weak equivalence) and
// the subspaces of dimension 1 are not considered in the search, since they are all weakly equivalent to S,
// which is added manually to the output; see stop_at_dim_2.
//
// Let k:=S/P, A:=T/P (a finite k-algebra; note that TP=P) and Q:=I/PI, which is an A-module.
// The fractional S-ideals J with PI c J c I correspond to the k-subspaces W of Q. We look for the W such that
//  - W.A = Q, which is equivalent to J*T=I, and
//  - Stab_A(W) = k, which is equivalent to (J:J)=S (see is_mult_ring_S),
// and we return one J for each orbit of such W's under the action of A^* (which induces the same orbits as
// (T_P)^*/(S_P)^*), since two such J's are weakly equivalent if and only if the corresponding W's are in the
// same orbit.
// The search goes down one dimension at a time, starting from Q and taking maximal subspaces. If W.A ne Q, then
// the same holds for every subspace of W, so such W are discarded. Both properties, as well as taking maximal
// subspaces, are compatible with the action of A^*: hence, at each dimension, it suffices to continue the search
// from one representative of each orbit.
    S:=Order(P);
    T:=Order(I);
    assert T eq MultiplicatorRing(P);
    stop_at_dim_2:=false;
    if IsInvertible(I) then
        I:=OneIdeal(T);
        stop_at_dim_2:=true;
    end if;
    TP:=T!!P;
    PI:=TP*I;
    IS:=S!!I;
    PIS:=S!!PI;
    zbPI:=ZBasis(PI);
    Q,q:=QuotientVS(IS,PIS,P); // q:I->I/PI=Q
    dimQ:=Dimension(Q);
    k:=Field(Q);
    MS:=MatrixRing(k,dimQ);
    // mat(t) is the matrix in MS representing the multiplication by t on Q, 
    // acting on the right: q(v*t) = q(v)*mat(t).
    // Its rows are the images of the standard basis vectors of Q.
    mat:=func< t | MS!Matrix([ q((Q.i@@q)*t) : i in [1..dimQ] ]) >;
    // The k-span of the images of a Z-basis of T is the image of A=T/P in End_k(Q):
    // it contains the identity and it is closed under multiplication.
    A_space:=sub<MS | [ mat(t) : t in ZBasis(T) ]>;
    A_basis:=Basis(A_space);
    // If A->End_k(Q) is not injective, then its kernel is (PI:I)/P, which is not zero, so (PI:I) is not contained
    // in S. For every x in (PI:I) and every J as above, we have xJ c xI c PI c J, so (J:J) ne S. 
    // The output is empty.
    // This cannot happen if I is invertible.
    dimA:=Ilog(#k,Integers()!Index(T,TP)); // dim_k T/P
    assert Dimension(A_space) le dimA;
    if Dimension(A_space) lt dimA then
        assert not stop_at_dim_2;
        return [];
    end if;
    // Matrices representing the action of generators of A^* on Q. Scalar matrices act trivially on subspaces.
    U_gens:=[ g : g in Seqset([ mat(g) : g in gensU ]) | not IsScalar(g) ];

    orbit:=function(W)
    // the orbit of the subspace W under A^*. The group is finite, so the closure under the generators suffices.
        orb:={W};
        frontier:={W};
        repeat
            new:={ sub<Q|[ (Q!X.i)*g : i in [1..Ngens(X)] ]> : X in frontier, g in U_gens } diff orb;
            orb join:=new;
            frontier:=new;
        until IsEmpty(new);
        return orb;
    end function;

    has_trivial_extension:=function(W)
    // returns whether W.A = Q, that is, whether J*T=I for J=q^-1(W).
        return Dimension(sub<Q|[ (Q!W.i)*a : a in A_basis, i in [1..Ngens(W)] ]>) eq dimQ;
    end function;

    output:=stop_at_dim_2 select [OneIdeal(S)] else [];
    reps:=[Q]; // representatives of the orbits of the subspaces of the current dimension with trivial extension.
               // Q itself never contributes to the output, since (I:I) contains T, which is strictly bigger than S.
    dim:=dimQ;
    min_dim:=stop_at_dim_2 select 2 else 1;
    while dim gt min_dim and #reps gt 0 do
        seen:={}; // subspaces of dimension dim-1 already considered: whole orbits for those with trivial extension
        new_reps:=[];
        for W in reps do
            for M in MaximalSubmodules(W) do
                if M in seen then
                    continue;
                end if;
                Include(~seen,M);
                if not has_trivial_extension(M) then
                    continue;
                end if;
                seen join:=orbit(M);
                Append(~new_reps,M);
                if is_mult_ring_S(Q,k,A_basis,M) then
                    Append(~output,Ideal(S,[ (Q!b)@@q : b in Basis(M) ] cat zbPI));
                end if;
            end for;
        end for;
        reps:=new_reps;
        dim-:=1;
    end while;
    return output;
end function;

