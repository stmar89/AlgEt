///## Weak equivalence class monoid as a sequence of representatives.
/// Since the multiplicator ring is an invariant of the weak equivalence class of a fractional $R$-ideal, we have a partitioning $\mathcal{W}(R) = \bigsqcup_S \mathcal{W}_S(R)$, where the disjoint union is taken over the overorders $S$ of $R$ and $\mathcal{W}_S(R)$ is the subset of $\mathcal{W}(R)$ consisting of the weak equivalence classes of fractional $R$-ideals with multiplicator ring $S$.
/// Let $S$ be an overorder of $R$. If $S$ is Gorenstein then $\mathcal{W}_S(R)$ consists only of the class defined by $S$. If $S$ has Cohen-Macaulay type $2$ and $\mathfrak{p}$ is a prime of $S$, then each fractional $R$-ideal $I$ with multiplicator ring $S$ satisfies either $I_\mathfrak{p} \simeq S_\mathfrak{p}$ or $I_\mathfrak{p} \simeq S^t_\mathfrak{p}$. The second possibility occurs precisely when $S$ has Cohen-Macaulay type $2$ at the primes $\mathfrak{p}$. This classification results provide a very efficient method to compute $\mathcal{W}_S(R)$ for orders $S$ with Cohen-Macaulay type $\leq 2$. For the general case, an algorithm that includes a more expensive enumeration step is provided.
///
/// For further details, see:
/// - Stefano Marseglia, "Cohen-Macaulay type of orders, generators and ideal classes", Journal of Algebra 658 (2024), 247-276.
/// - Stefano Marseglia, "Local isomorphism classes of fractional ideals of orders in étale algebras", Journal of Algebra 673 (2025), 77-102.

/// Given an order $S$, returns representatives $I$ of all weak equivalence classes of fractional $S$-ideals satisfying $(I:I)=S$.
intrinsic WeakEquivalenceClassesWithPrescribedMultiplicatorRing(S::AlgEtQOrd) -> SeqEnum[AlgEtQIdl]
{Given an order S, returns representatives I of all weak equivalence classes of fractional S-ideals satisfying (I:I)=S.}
    return WKICM_bar(S);
end intrinsic;

///ditto
intrinsic WKICM_bar(S::AlgEtQOrd) -> SeqEnum[AlgEtQIdl]
{ " } // "
    if not assigned S`WKICM_bar then
        if IsGorenstein(S) then
            vprintf WKICM_bar,2 : " Gorenstein case\n";
            S`WKICM_bar:=[OneIdeal(S)];
        elif CohenMacaulayType(S) eq 2 then
            vprintf WKICM_bar,2 : " Cohen Macaulay type 2 case\n";
            S`WKICM_bar:=wkicm_bar_CM_type2(S,NonGorensteinPrimes(S));
        else
            vprintf WkClasses,2:"Order of CohenMacaulayType = %o\n",CohenMacaulayType(S);
            // general case
            seqWk_bar:=[];
            pp:=SingularPrimes(S);
            if #pp eq 1 then
                vprint WKICM_bar,2 : "WKICM_bar: type >2, only 1 singular prime";
                P:=pp[1];
                T:=MultiplicatorRing(P);
                // if S^tT is invertible, then I don't need all WKICM_bar(T), but only the invertible class.
                if IsInvertible(T!!TraceDualIdeal(S)) then
                    wkT:=[ OneIdeal(T) ];
                else
                    wkT:=$$(T);
                end if;
                gensU:=units_T_mod_P_gens(T,P); // generators of (T/P)^*, the same for every J in wkT
                for J in wkT do
                    seqWk_bar_J:=wkicm_bar_with_P_P(J,P,gensU);
                    for I in seqWk_bar_J do
                        ZBasisLLL(I);
                    end for;
                    Append(~seqWk_bar,seqWk_bar_J);
                end for;
                vprintf WKICM_bar,2 : "sizes of seqWk_bar_J = %o\n",[#x : x in seqWk_bar];
                seqWk_bar:=&cat(seqWk_bar);
                assert2 forall{ J : J in seqWk_bar | MultiplicatorRing(J) eq S };
                assert2 forall{ J : J in seqWk_bar | not exists{ I : I in seqWk_bar | I ne J and IsWeakEquivalent(I,J) } };
                S`WKICM_bar:=seqWk_bar;
            else
                vprint WKICM_bar,2 : "WKICM_bar: type >2, more than 1 singular prime";
                O:=MaximalOrder(Algebra(S));
                wk_pp:=[];
                // We have W_bar(S) = \prod_P W_P_bar(S), where:
                //     - P runs over the singular primes of S,
                //     - W_bar(S) is the monoid of weak equivalence classes with mult ring S, and
                //     - W_P_bar(S) is monoid of local P-equivalence classes with mult ring equal to S at P.
                // We also have W_P_bar(S) = W_bar(S+P^kO), for any k big enough (eg. k ge v_p([O:S]),
                //       where p is the rational prime in P).
                ps:=[]; // rational primes of the pps
                for iP->P in pp do
                    t0:=Cputime();
                    vprintf WKICM_bar,2 : "We start the local computation at the %o-th singular prime.",iP;
                    wk_P:=[];
                    _,p:=IsPrimePower(Index(S,P));
                    Append(~ps,p);
                    k:=Valuation(Index(O,S),p);
                    SP:=Order(ZBasis(S) cat ZBasis(O!!P^k));
                    wk_P_bar:=$$(SP); // recursion
                    // wk_P = W_P(S) = W(S+P^k0O) in the notation above
                    wk_P_bar:=[ S !! I : I in wk_P_bar];
                    vprintf WKICM_bar,2 : "...Done in %o secs.\n",Cputime(t0);
                    Append(~wk_pp,wk_P_bar);
                end for;

                ///////////////////////////////
                // We now reconstruct W_bar(S) using the P-local parts W_P_bar(S) = W_bar(S+P^kO)
                //////////////////////////////
                wk_pp_idls:=[];
                pp_pows:=[];
                t1:=Cputime();
                vprintf WKICM_bar,2 : "We make all the local parts integral\n";
                for ip->wk in wk_pp do
                    wk_exps:=[];
                    wk_idls:=[];
                    for i in [1..#wk] do
                        I:=wk[i];
                        if not IsIntegral(I) then
                            I:=SmallRepresentative(I); // I c E with small norm
                        end if;
                        k:=Valuation(Index(S,I),ps[ip]);
                        Append(~wk_exps,k);
                        Append(~wk_idls,I);
                    end for;
                    k_ip:=Max(wk_exps);
                    Pk_ip:=pp[ip]^k_ip; // for every local representative I at pp[ip] we have that Pk_ip c I (locally)
                    ZBasisLLL(Pk_ip);
                    Append(~pp_pows,Pk_ip);
                    Append(~wk_pp_idls,wk_idls);
                end for;
                vprintf WKICM_bar,2 : "...Done in %o secs.\n",Cputime(t1);

                n:=#pp;
                t0:=Cputime();
                vprintf WKICM_bar,2 : "We compute the \prod_{j \\ne i} P_j^k_j\n";
                prod_j_ne_i:=[ ];
                for i in [1..n] do
                    // coprime ideals, so we can use meet instead of *, which is faster
                    prod:=&meet[ pp_pows[j] : j in [1..n] | j ne i ];
                    ZBasisLLL(prod);
                    Append(~prod_j_ne_i,prod);
                end for;
                vprintf WKICM_bar,2 : "\t...Done in %o secs.\n",Cputime(t0);

                t0:=Cputime();
                vprintf WKICM_bar,2 : "We modify each entry of the cartesian product\n";
                for ip in [1..n] do
                    for i in [1..#wk_pp_idls[ip]] do
                        I:=(wk_pp_idls[ip][i]+pp_pows[ip])*prod_j_ne_i[ip];
                        ZBasisLLL(I);
                        wk_pp_idls[ip][i]:=I;
                    end for;
                end for;
                vprintf WKICM_bar,2 : "\t...Done in %o secs.\n",Cputime(t0);

                t0:=Cputime();
                tot:=&*[#x : x in wk_pp_idls]; perc_old:=0; iI:=0;
                wk_pp_idls:=CartesianProduct(wk_pp_idls);
                vprintf WKICM_bar,2 : "We start patching together the local parts\n";
                wk:=[];
                for I_Ps in wk_pp_idls do
                    if GetVerbose("WKICM_bar") ge 3 then
                        iI +:=100; perc:=Truncate(iI/tot);
                        if perc gt perc_old then perc_old:=perc; printf "\t%o%% in %o secs\n",perc,Cputime(t0); end if;
                    end if;
                    J:=&+[ I_Ps[ip] : ip in [1..n] ];
                    // J satisfies: J = I_Ps[ip] locally at pp[ip] for every ip.
                    assert2 forall{ ip : ip in [1..n] |
                                                    (J+I_Ps[ip]) eq I_Ps[ip]+pp[ip]*(J+I_Ps[ip]) and
                                                    (J+I_Ps[ip]) eq J+pp[ip]*(J+I_Ps[ip])};
                    Append(~wk,J);
                end for;
                vprintf WKICM_bar,2 : "\t...Done in %o secs.\n",Cputime(t0);

                t0:=Cputime();
                vprintf WKICM_bar,2 : "We LLL all the ZBasis\n";
                for I in wk do
                    ZBasisLLL(I);
                end for;
                vprintf WKICM_bar,2 : "\t...Done in %o secs\n",Cputime(t0);

                t0:=Cputime();
                vprintf WKICM_bar,2 : "Checking assert2 ...\n";
                // asserts
                assert2 forall{ J : J in wk | Order(J) eq S };
                assert2 forall{ J : J in wk | not exists{I : I in wk | I ne J and IsWeakEquivalent(I,J) }  };
                vprintf WKICM_bar,2 : "\t...Done in %o secs\n",Cputime(t0);

                S`WKICM_bar:=wk;
            end if;
        end if;
    end if;
    // populate MultiplicatorRing, if not done before
    for i in [1..#S`WKICM_bar] do
        I:=S`WKICM_bar[i];
        if not assigned I`MultiplicatorRing then
            I`MultiplicatorRing:=S;
        end if;
    end for;
    return S`WKICM_bar;
end intrinsic;

/// Given an order $E$, returns a set of representatives of the weak equivalence class monoid $\mathcal{W}(E)$.
intrinsic WeakEquivalenceClassMonoid(E::AlgEtQOrd)->SeqEnum[AlgEtQIdl]
{Given an order E, returns a set of representatives of the weak equivalence class monoid of E.}
    return WKICM(E);
end intrinsic;

///ditto
intrinsic WKICM(E::AlgEtQOrd)->SeqEnum[AlgEtQIdl]
{ " } // "
    if not assigned E`WKICM then
        pp:=SingularPrimes(E);
        if #pp eq 0 then
            E`OverOrders:=[E];
            E`WKICM:=[OneIdeal(E)]; // the order is maximal
            E`WKICM_bar:=[OneIdeal(E)]; // the order is maximal
        elif #pp eq 1 then // 1 singular prime: go for the recursion
            vprintf WKICM,2 : "There is only one singular prime.\n";
            // W(E) = union_{ S in MinimalOverOrders(E)} W(S) disjoint_union WKICM_bar(E);
            // The first union should be made in a smart way!
            min:=MinimalOverOrders(E);
            for S in min do
                _:=$$(S); // recursion to populate
            end for;
            // We want to put in oo_E the strict overorders of E, from the overorders of the minimal overorders.
            // There will be a lot of overlap. So we try to do it in a smart way.
            t0:=Cputime();
            vprintf WKICM,2 : "\tWe merge the overorders of the minimal overorders.";
            oo_E:={@ @}; // the repetitions are removed using the intrinsic Hash for orders
            for S in min do
                for T in OverOrders(S) do
                    Include(~oo_E,T);
                end for;
            end for;
            oo_E:=IndexedSetToSequence(oo_E); // does not contain E.
            vprintf WKICM,2 : "...Done in %o secs.\n",Cputime(t0);
            assert2 forall{ S : S in oo_E | assigned S`WKICM_bar };
            wk_mins:=&cat[ [ E !! I : I in WKICM_bar(S)] : S in oo_E ];
            oo_E:=[E] cat oo_E;
            sort_overorders(~oo_E); // as in OverOrders: E comes first
            E`OverOrders:=oo_E;
            E`WKICM:=WKICM_bar(E) cat wk_mins;
        else //more then 1 singular prime: divide and patch
            vprintf WKICM,2 : "There are %o singular primes.\n",#pp;
            O:=MaximalOrder(Algebra(E));
            wk_pp:=[];
            // We have W(E) = \prod_P W_P(E), where:
            //     - P runs over the singular primes of E,
            //     - W(E) is the monoid of weak equivalence classes, and
            //     - W_P(E) is monoid of local P-equivalence classes.
            // We also have W_P(E) = W(E+P^kO), for any k big enough (eg. k ge v_p([O:E]),
            //       where p is the rational prime of P).
            ps:=[]; // rational primes of the pps
            for iP->P in pp do
                t0:=Cputime();
                vprintf WKICM,2 : "We start the local computation at the %o-th singular prime.",iP;
                wk_P:=[];
                _,p:=IsPrimePower(Index(E,P));
                Append(~ps,p);
                k:=Valuation(Index(O,E),p);
                EP:=Order(ZBasis(E) cat ZBasis(O!!P^k)); // EP is an overorder of E, locally equal to E at P,
                                                         // and to the maximal order O at every other prime.
                                                         // In particular, EP has a unique singular prime,
                                                         // which is the extension of P.
                wk_P:=$$(EP); // recursion
                // wk_P = W_P(E) = W(E+O!!P^k) in the notation above
                wk_P:=[ E !! I : I in wk_P];
                vprintf WKICM,2 : "...Done in %o secs.\n",Cputime(t0);
                Append(~wk_pp,wk_P);
            end for;
            // We now reconstruct W(E) using the P-local parts W_P(E) = W(E+P^kO)
            wk_pp_idls:=[];
            pp_pows:=[];
            t1:=Cputime();
            vprintf WKICM,2 : "We make all the local parts integral\n";
            for ip->wk in wk_pp do
                wk_exps:=[];
                wk_idls:=[];
                for i in [1..#wk] do
                    I:=wk[i];
                    if not IsIntegral(I) then
                        I:=SmallRepresentative(I); // I c E with small norm
                    end if;
                    k:=Valuation(Index(E,I),ps[ip]);
                    Append(~wk_exps,k);
                    Append(~wk_idls,I);
                end for;
                k_ip:=Max(wk_exps);
                Pk_ip:=pp[ip]^k_ip; // for every local representative I at pp[ip] we have that Pk_ip c I (locally)
                ZBasisLLL(Pk_ip);
                Append(~pp_pows,Pk_ip);
                Append(~wk_pp_idls,wk_idls);
            end for;
            vprintf WKICM,2 : "...Done in %o secs.\n",Cputime(t1);

            n:=#pp;
            t0:=Cputime();
            vprintf WKICM,2 : "We compute the \prod_{j \\ne i} P_j^k_j\n";
            prod_j_ne_i:=[ ];
            for i in [1..n] do
                // coprime ideals, so we can use meet instead of *, which is faster
                prod:=&meet[ pp_pows[j] : j in [1..n] | j ne i ];
                ZBasisLLL(prod);
                Append(~prod_j_ne_i,prod);
            end for;
            vprintf WKICM,2 : "\t...Done in %o secs.\n",Cputime(t0);

            t0:=Cputime();
            vprintf WKICM,2 : "We modify each entry of the cartesian product\n";
            for ip in [1..n] do
                for i in [1..#wk_pp_idls[ip]] do
                    I:=(wk_pp_idls[ip][i]+pp_pows[ip])*prod_j_ne_i[ip];
                    ZBasisLLL(I);
                    wk_pp_idls[ip][i]:=I;
                end for;
            end for;
            vprintf WKICM,2 : "\t...Done in %o secs.\n",Cputime(t0);

            t0:=Cputime();
            tot:=&*[#x : x in wk_pp_idls]; perc_old:=0; iI:=0;
            wk_pp_idls:=CartesianProduct(wk_pp_idls);
            vprintf WKICM,2 : "We start patching together the local parts\n";
            wk:=[];
            for I_Ps in wk_pp_idls do
                if GetVerbose("WKICM") ge 3 then
                    iI +:=100; perc:=Truncate(iI/tot);
                    if perc gt perc_old then perc_old:=perc; printf "\t%o%% in %o secs\n",perc,Cputime(t0); end if;
                end if;
                J:=&+[ I_Ps[ip] : ip in [1..n] ];
                // J satisfies: J = I_Ps[ip] locally at pp[ip] for every ip.
                assert2 forall{ ip : ip in [1..n] |
                                                (J+I_Ps[ip]) eq I_Ps[ip]+pp[ip]*(J+I_Ps[ip]) and
                                                (J+I_Ps[ip]) eq J+pp[ip]*(J+I_Ps[ip])};
                Append(~wk,J);
            end for;
            vprintf WKICM,2 : "\t...Done in %o secs.\n",Cputime(t0);

            t0:=Cputime();
            vprintf WKICM,2 : "We LLL all the ZBasis\n";
            for I in wk do
                ZBasisLLL(I);
            end for;
            vprintf WKICM,2 : "\t...Done in %o secs\n",Cputime(t0);

            t0:=Cputime();
            vprintf WKICM,2 : "Checking assert2 ...\n";
            // asserts
            assert2 forall{ J : J in wk | Order(J) eq E };
            assert2 forall{ J : J in wk | not exists{I : I in wk | I ne J and IsWeakEquivalent(I,J) }  };
            vprintf WKICM,2 : "\t...Done in %o secs\n",Cputime(t0);

            E`WKICM:=wk;

            // We populate the attributes E`OverOrders and S`WKICM_bar for each overorder.
            // This is needed for the recursion step.
            // The overorders of E are the multiplicator rings of the classes in wk:
            // we collect them in an indexed set and sort them as in OverOrders using sort_overorders.
            // Some of the overorders have already the vararg WKICM_bar populated, because, for
            // example, they were coming from the recursive-1-single-singular-prime part.
            // For the ones without WKICM_bar, we collect the classes with that multiplicator ring in an
            // AssociativeArray, keyed by the order. Both use the intrinsic Hash for orders.
            t0:=Cputime();
            vprintf WKICM,2 : "We start populating the varargs OverOrders and WKICM_bar.\n";
            if not assigned E`OverOrders then
                oo_E:={@ @};
                wk_bar:=AssociativeArray();
                for I in wk do
                    S:=MultiplicatorRing(I);
                    Include(~oo_E,S);
                    if not assigned S`WKICM_bar then
                        if IsDefined(wk_bar,S) then
                            Append(~wk_bar[S],S!!I);
                        else
                            wk_bar[S]:=[S!!I];
                        end if;
                    end if;
                end for;
                for S in Keys(wk_bar) do
                    T:=S; // T and S are the same object: attributes cannot be assigned to the loop variable
                    T`WKICM_bar:=wk_bar[S];
                end for;
                oo_E:=IndexedSetToSequence(oo_E);
                sort_overorders(~oo_E); // as in OverOrders
                assert2 E in oo_E;
                E`OverOrders:=oo_E;
            end if;
            vprintf WKICM,2 : "\t...Done in %o secs.\n",Cputime(t0);
            assert2 &+[ #S`WKICM_bar : S in OverOrders(E) ] eq #wk;
        end if;
    end if;

    return E`WKICM;
end intrinsic;

