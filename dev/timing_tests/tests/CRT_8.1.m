    equation order E of f = (x^8+16)(x^8+81), and for 300 tuples modulo all the 6 primes of the conductor.
    Why: the conductor of E has 6 primes with residue fields F_2, F_3, F_5^4 (twice) and F_13^4 (twice): the two-ideal
    CRT works with the HNF transformation of the stacked Z-bases (precomputed once per ideal), the sequence version
    recurses with intersections of the remaining ideals. The same primes as in PicardGroup_1.3.
    Inputs (fixed, see README): the 6 primes (from PrimesAbove with a2f3804 on 2026-11-10, sorted by their minimal
    integer) stored as Z-bases in a fixed order; the elements come from the Lehmer generator below (state 1).
*/
