/*
    IdealOps_2.3: arithmetic of ideals of the equation order E of f = (x^8+16)(x^8+81): 600 sums, 600 products,
    600 colon ideals and 600 intersections of pairs of ideals with 3 generators, then the 600 trace dual ideals.
    Why: an algebra of dimension 16 with 2 components and an equation order of huge index (~2.8 10^24), where every
    operation goes through a 16x16 (or 32x16) HNF over Z with large entries: sums and products are generated by
    products of generators, colon ideals and intersections by the dual-lattice and the stacked-HNF constructions.
    The elementary operations behind every other test.
    Inputs (fixed, see README): the generators come from the Lehmer generator below (state 1).
*/
AttachSpec(spec);
SetSeed(1);
_<x>:=PolynomialRing(Integers());
// Fixed inputs (see README): a checksum of the coordinates of a sequence of elements, printed and asserted below.
checksum:=function(elts)
    s:=0;
    for z in elts do
        for c in Components(z) do
            for q in Eltseq(c) do
                s:=(1000003*s+7*Numerator(q)+Denominator(q)) mod (2^61-1);
            end for;
        end for;
    end for;
    return s;
end function;
// N pseudo-random elements with coefficients in [-3..3] on the powers of the primitive element of A, from a Lehmer
// generator with state s: the same elements in every Magma version, unlike Random. Returns them and the new state.
lehmer_elts:=function(A,N,s)
    F:=PrimitiveElement(A);
    pw:=[ F^i : i in [0..Dimension(A)-1] ];
    out:=[];
    for k in [1..N] do
        cs:=[];
        for i in [1..#pw] do
            s:=(48271*s) mod (2^31-1);
            Append(~cs,(s mod 7)-3);
        end for;
        Append(~out,&+[ cs[i]*pw[i] : i in [1..#pw] ]);
    end for;
    return out,s;
end function;
f:=(x^8+16)*(x^8+81);
A:=EtaleAlgebra(f);
assert [ DefiningPolynomial(K) : K in Components(A) ] eq [ x^8+16, x^8+81 ];
E:=EquationOrder(A);
s:=1;
gens:=[];
for i in [1..1200] do
    gs,s:=lehmer_elts(A,3,s);
    Append(~gens,gs);
end for;
ids:=[ Ideal(E,gens[i]) : i in [1..600] ];
jds:=[ Ideal(E,gens[i]) : i in [601..1200] ];
chk:=checksum(&cat gens);
printf "### INPUT %o\n",chk;
assert chk eq 1745128687236963994;
t0:=Cputime();
    sums:=[ ids[i]+jds[i] : i in [1..600] ];
    prods:=[ ids[i]*jds[i] : i in [1..600] ];
    cols:=[ ColonIdeal(ids[i],jds[i]) : i in [1..600] ];
    meets:=[ ids[i] meet jds[i] : i in [1..600] ];
    duals:=[ TraceDualIdeal(I) : I in ids ];
t:=Cputime(t0);
assert forall{ i : i in [1..600] | meets[i] subset ids[i] and ids[i] subset sums[i] and prods[i] subset meets[i] };
printf "### TIMING %o %o\n",name,t;
