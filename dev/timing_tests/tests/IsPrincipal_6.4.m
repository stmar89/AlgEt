/*
    IsPrincipal_6.4: IsPrincipal (GRH), with the generator, on principal ideals I^n of the equation orders of
    f = x^8 + 3^8 7 (450 ideals), of f = x^4-1000x^3-1000x^2-1000x-1000 (60) and of A = K x K, K the CM quartic field
    of x^4+x^2+529 (600), where n is the order of the class of I in Pic(E) (PicardGroup and the powers are not timed).
    Why: the generator of a principal ideal is obtained from a generator of IO and a coset representative in the unit
    group of O. For x^8 + 3^8 7 (a CM octic field with trivial Cl(O), unit rank 3, [O:E] = 2^6 3^28, #Pic(E) =
    1259712) n is mostly 432; for the quartic (signature (2,1), Cl(O) = Z/3548, #Pic(E) = 3548000) n goes up to
    88700, so I^n has a huge Z-basis and IO is principal only after the product with Cl(O) representatives; for
    K x K (two identical components, Cl(O) = (Z/5)^2, unit rank 2) n is mostly 300. These ideals are the ones that
    PicardGroup builds to glue the Picard groups.
    Inputs (fixed, see README): I runs over the first invertible ideals generated by two elements of the Lehmer
    generator below (state 1) whose class is not trivial; I^n is taken through its HNF basis. Replaces
    IsPrincipal_6.2 (two principal ideals of the first order, with 3 seeds each, about 0.4 s with 9362a5e).
*/
AttachSpec(spec);
SetSeed(1);
SetClassGroupBounds("GRH");
_<x>:=PolynomialRing(Integers());
// Fixed inputs (see README): a checksum of the coordinates of a sequence of elements, printed and asserted below.
checksum:=function(elts)
    s:=0;
    for z in elts do
        for c in Components(z) do
            for q in Eltseq(c) do
                s:=(1000003*s+7*Numerator(q)+Denominator(q)) mod (2^61-1);
            end for;
        end for;
    end for;
    return s;
end function;
// N pseudo-random elements with coefficients in [-3..3] on the powers of the primitive element of A, from a Lehmer
// generator with state s: the same elements in every Magma version, unlike Random. Returns them and the new state.
lehmer_elts:=function(A,N,s)
    F:=PrimitiveElement(A);
    pw:=[ F^i : i in [0..Dimension(A)-1] ];
    out:=[];
    for k in [1..N] do
        cs:=[];
        for i in [1..#pw] do
            s:=(48271*s) mod (2^31-1);
            Append(~cs,(s mod 7)-3);
        end for;
        Append(~out,&+[ cs[i]*pw[i] : i in [1..#pw] ]);
    end for;
    return out,s;
end function;
// The first N invertible ideals of S generated by two Lehmer elements (non-zero-divisors), starting from state s.
// Returns the ideals, their generators and the new state.
lehmer_inv_ideals:=function(S,N,s)
    A:=Algebra(S);
    out:=[]; gens:=[];
    while #out lt N do
        gs,s:=lehmer_elts(A,2,s);
        if exists{ g : g in gs | IsZeroDivisor(g) } then continue; end if;
        I:=Ideal(S,gs);
        if IsInvertible(I) then Append(~out,I); Append(~gens,gs); end if;
    end while;
    return out,gens,s;
end function;
K:=NumberField(x^4+x^2+529);
data:=[* <[NumberField(x^8+3^8*7)],450>, <[NumberField(x^4-1000*(x^3+x^2+x+1))],60>, <[K,K],600> *];
chks:=[];
t:=0;
for d in data do
    As,N:=Explode(d);
    A:=EtaleAlgebra(As);
    E:=EquationOrder(A);
    P,p:=PicardGroup(E : GRH:=true);
    Is:=[]; s:=1;
    while #Is lt N do
        I,gs,s:=lehmer_inv_ideals(E,1,s);
        n:=Order(I[1]@@p);
        if n gt 1 then Append(~Is,<Ideal(E,ZBasis(Ideal(E,ZBasis(I[1]^n)))),n>); end if;
    end while;
    Append(~chks,checksum(&cat[ ZBasis(I[1]) : I in Is ]));
    gens:=[];
    t0:=Cputime();
        for I in Is do
            test,gen:=IsPrincipal(I[1] : GRH:=true);
            assert test;
            Append(~gens,gen);
        end for;
    t+:=Cputime(t0);
    assert forall{ i : i in [1..5] | gens[i]*E eq Is[i][1] };
end for;
printf "### INPUT %o\n",chks;
printf "### TIMING %o %o\n",name,t;
print "### DONE";
quit;
