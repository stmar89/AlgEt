/*
    PicardGroup_1.10: 7500 discrete logarithms in Pic(E), each followed by the representative of the class, for the
    equation orders E of f = x^4-1000x^3-1000x^2-1000x-1000, x^6-100(x^5+x^4+x^3+x^2+x+1) and x^8+3^8 7 (2500 in
    each; PicardGroup itself is not timed).
    Why: a discrete logarithm takes a small coprime representative, finds its class in Cl(O) with Magma, divides by
    the corresponding power product of the generators of Cl(O), tests the result for principality in O and maps the
    generator to the residue ring (O/f)^*. The three orders have different Cl(O) and (O/f)^*: Z/3548 and
    #Pic(E) = 3548000 (signature (2,1)), Cl(O) = Z/2 x Z/2 x Z/2196 and #Pic(E) = 3513600 (a
    sextic), trivial Cl(O) and #Pic(E) = 1259712 (a CM octic, see IsPrincipal_6.3).
    Inputs (fixed, see README): the first 2500 invertible ideals generated by two elements of the Lehmer generator
    below (state 1), in each order. Replaces PicardGroup_1.4 (50 discrete logarithms in the first order, about 12 s
    with 9362a5e).
*/
AttachSpec(spec);
SetSeed(1);
SetClassGroupBounds("GRH");
_<x>:=PolynomialRing(Integers());
// Fixed inputs (see README): a checksum of the coordinates of a sequence of elements, printed and asserted below.
checksum:=function(elts)
    s:=0;
    for z in elts do
        for c in Components(z) do
            for q in Eltseq(c) do
                s:=(1000003*s+7*Numerator(q)+Denominator(q)) mod (2^61-1);
            end for;
        end for;
    end for;
    return s;
end function;
// N pseudo-random elements with coefficients in [-3..3] on the powers of the primitive element of A, from a Lehmer
// generator with state s: the same elements in every Magma version, unlike Random. Returns them and the new state.
lehmer_elts:=function(A,N,s)
    F:=PrimitiveElement(A);
    pw:=[ F^i : i in [0..Dimension(A)-1] ];
    out:=[];
    for k in [1..N] do
        cs:=[];
        for i in [1..#pw] do
            s:=(48271*s) mod (2^31-1);
            Append(~cs,(s mod 7)-3);
        end for;
        Append(~out,&+[ cs[i]*pw[i] : i in [1..#pw] ]);
    end for;
    return out,s;
end function;
// The first N invertible ideals of S generated by two Lehmer elements (non-zero-divisors), starting from state s.
// Returns the ideals, their generators and the new state.
lehmer_inv_ideals:=function(S,N,s)
    A:=Algebra(S);
    out:=[]; gens:=[];
    while #out lt N do
        gs,s:=lehmer_elts(A,2,s);
        if exists{ g : g in gs | IsZeroDivisor(g) } then continue; end if;
        I:=Ideal(S,gs);
        if IsInvertible(I) then Append(~out,I); Append(~gens,gs); end if;
    end while;
    return out,gens,s;
end function;
polys:=[ x^4-1000*(x^3+x^2+x+1), x^6-100*(x^5+x^4+x^3+x^2+x+1), x^8+3^8*7 ];
sizes:=[ 3548000, 3513600, 1259712 ];
chks:=[];
t:=0;
for i->f in polys do
    A:=EtaleAlgebra(f);
    E:=EquationOrder(A);
    Is,gens:=lehmer_inv_ideals(E,2500,1);
    Append(~chks,checksum(&cat gens));
    P,p:=PicardGroup(E : GRH:=true);
    assert #P eq sizes[i];
    gs:=[];
    t0:=Cputime();
        for I in Is do
            g:=I@@p;
            J:=p(g);
            Append(~gs,g);
        end for;
    t+:=Cputime(t0);
    assert forall{ j : j in [1..5] | (p(gs[j]))@@p eq gs[j] };
end for;
printf "### INPUT %o\n",chks;
assert chks eq [ 2047221371672984981, 2033037433145162143, 1962238692644160072 ];
printf "### TIMING %o %o\n",name,t;
print "### DONE";
quit;
