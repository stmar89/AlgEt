/*
    PicardGroup_1.11: PicardGroup and UnitGroup (GRH) of the equation order E of A = K x K x K, K the CM quartic
    field of x^4+x^2+529, followed by 4500 discrete logarithms, each followed by the representative of the class.
    Why: three identical components (the same number field object), Cl(O) = (Z/5)^3 and a unit group of rank 3;
    [O:E] = 2^38 3^18 11^4 17^2 23^3 41^2 59 941^2, so (O/f)^* is huge and Pic(E) has 67852818829292596730265600000
    elements. The discrete logarithms work with ideals of a big index in a product algebra of dimension 12.
    Inputs (fixed, see README): the first 4500 invertible ideals generated by two elements of the Lehmer generator
    below (state 1). Replaces PicardGroup_1.5 (K x K with 20 discrete logarithms, about 3 s with 9362a5e).
*/
AttachSpec(spec);
SetSeed(1);
SetClassGroupBounds("GRH");
_<x>:=PolynomialRing(Integers());
// Fixed inputs (see README): a checksum of the coordinates of a sequence of elements, printed and asserted below.
checksum:=function(elts)
    s:=0;
    for z in elts do
        for c in Components(z) do
            for q in Eltseq(c) do
                s:=(1000003*s+7*Numerator(q)+Denominator(q)) mod (2^61-1);
            end for;
        end for;
    end for;
    return s;
end function;
// N pseudo-random elements with coefficients in [-3..3] on the powers of the primitive element of A, from a Lehmer
// generator with state s: the same elements in every Magma version, unlike Random. Returns them and the new state.
lehmer_elts:=function(A,N,s)
    F:=PrimitiveElement(A);
    pw:=[ F^i : i in [0..Dimension(A)-1] ];
    out:=[];
    for k in [1..N] do
        cs:=[];
        for i in [1..#pw] do
            s:=(48271*s) mod (2^31-1);
            Append(~cs,(s mod 7)-3);
        end for;
        Append(~out,&+[ cs[i]*pw[i] : i in [1..#pw] ]);
    end for;
    return out,s;
end function;
// The first N invertible ideals of S generated by two Lehmer elements (non-zero-divisors), starting from state s.
// Returns the ideals, their generators and the new state.
lehmer_inv_ideals:=function(S,N,s)
    A:=Algebra(S);
    out:=[]; gens:=[];
    while #out lt N do
        gs,s:=lehmer_elts(A,2,s);
        if exists{ g : g in gs | IsZeroDivisor(g) } then continue; end if;
        I:=Ideal(S,gs);
        if IsInvertible(I) then Append(~out,I); Append(~gens,gs); end if;
    end while;
    return out,gens,s;
end function;
K:=NumberField(x^4+x^2+529);
A:=EtaleAlgebra([K,K,K]);
E:=EquationOrder(A);
Is,gens:=lehmer_inv_ideals(E,4500,1);
chk:=checksum(&cat gens);
printf "### INPUT %o\n",chk;
assert chk eq 1481628976068224003;
gs:=[];
t0:=Cputime();
    P,p:=PicardGroup(E : GRH:=true);
    U,u:=UnitGroup(E : GRH:=true);
    for I in Is do
        g:=I@@p;
        J:=p(g);
        Append(~gs,g);
    end for;
t:=Cputime(t0);
assert #P eq 67852818829292596730265600000;
assert forall{ i : i in [1..5] | (p(gs[i]))@@p eq gs[i] };
printf "### TIMING %o %o\n",name,t;
print "### DONE";
quit;
