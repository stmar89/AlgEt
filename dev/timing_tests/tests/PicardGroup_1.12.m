/*
    PicardGroup_1.12: the three number field examples of Klueners-Pauli, "Computing residue class rings and Picard
    groups of orders" (J. Algebra 2005): PicardGroup (GRH) of the equation orders, compared with Magma's RngOrd
    PicardGroup (not timed), plus 90 discrete logarithms in each, of the powers I^2000, I^4000 and I^8000 of 30
    ideals I, each followed by the representative of the class.
    Why: Z[2000^(1/3)] (Pic = Z/24, [O:E] = 1000, singular primes above 2 and 5), the cubic order of
    x^3-12x^2-6324x+459510 (Pic = Z/3 x Z/6 x Z/6 x Z/18, [O:E] = 193715, 4 singular primes) and the quintic order of
    x^5-1389x^4+512066x^3-11859166x^2+83453925x-211865821 (Pic = Z/2 x Z/2 x Z/2 x Z/24, Cl(O) = Z/12,
    [O:E] ~ 5 10^18 with a singular prime above 451251861947287): the reference examples of the algorithm, with
    small Picard groups but one huge index. The powers have Z-bases with thousands of digits, so a discrete
    logarithm first has to find a small coprime representative; the quintic order takes most of the time.
    Inputs (fixed, see README): the first 30 invertible ideals generated by two elements of the Lehmer generator
    below (state 1), in each order; the powers are taken through their HNF bases. Replaces PicardGroup_1.6 (10
    discrete logarithms of small ideals in each order, about 1 s with 9362a5e).
*/
AttachSpec(spec);
SetSeed(1);
SetClassGroupBounds("GRH");
_<x>:=PolynomialRing(Integers());
// Fixed inputs (see README): a checksum of the coordinates of a sequence of elements, printed and asserted below.
checksum:=function(elts)
    s:=0;
    for z in elts do
        for c in Components(z) do
            for q in Eltseq(c) do
                s:=(1000003*s+7*Numerator(q)+Denominator(q)) mod (2^61-1);
            end for;
        end for;
    end for;
    return s;
end function;
// N pseudo-random elements with coefficients in [-3..3] on the powers of the primitive element of A, from a Lehmer
// generator with state s: the same elements in every Magma version, unlike Random. Returns them and the new state.
lehmer_elts:=function(A,N,s)
    F:=PrimitiveElement(A);
    pw:=[ F^i : i in [0..Dimension(A)-1] ];
    out:=[];
    for k in [1..N] do
        cs:=[];
        for i in [1..#pw] do
            s:=(48271*s) mod (2^31-1);
            Append(~cs,(s mod 7)-3);
        end for;
        Append(~out,&+[ cs[i]*pw[i] : i in [1..#pw] ]);
    end for;
    return out,s;
end function;
// The first N invertible ideals of S generated by two Lehmer elements (non-zero-divisors), starting from state s.
// Returns the ideals, their generators and the new state.
lehmer_inv_ideals:=function(S,N,s)
    A:=Algebra(S);
    out:=[]; gens:=[];
    while #out lt N do
        gs,s:=lehmer_elts(A,2,s);
        if exists{ g : g in gs | IsZeroDivisor(g) } then continue; end if;
        I:=Ideal(S,gs);
        if IsInvertible(I) then Append(~out,I); Append(~gens,gs); end if;
    end while;
    return out,gens,s;
end function;
polys:=[ x^3-2000, x^3-12*x^2-6324*x+459510, x^5-1389*x^4+512066*x^3-11859166*x^2+83453925*x-211865821 ];
exps:=[ [24], [3,6,6,18], [2,2,2,24] ];
chks:=[];
t:=0;
for i->f in polys do
    A:=EtaleAlgebra(f);
    E:=EquationOrder(A);
    Is,gens:=lehmer_inv_ideals(E,30,1);
    Append(~chks,checksum(&cat gens));
    Js:=[ Ideal(E,ZBasis(Ideal(E,ZBasis(I^k)))) : k in [2000,4000,8000], I in Is ];
    gs:=[];
    t0:=Cputime();
        P,p:=PicardGroup(E : GRH:=true);
        for J in Js do
            g:=J@@p;
            JJ:=p(g);
            Append(~gs,g);
        end for;
    t+:=Cputime(t0);
    assert AbelianInvariants(P) eq exps[i];
    assert #P eq #PicardGroup(EquationOrder(NumberField(f)));
    assert forall{ j : j in [1..3] | (p(gs[j]))@@p eq gs[j] };
end for;
printf "### INPUT %o\n",chks;
assert chks eq [ 617778070790246284, 755469625192046807, 1298627734344971808 ];
printf "### TIMING %o %o\n",name,t;
print "### DONE";
quit;
